<?php

declare(strict_types=1);

namespace Lucasp\Loom\Tools\Regions;

use RuntimeException;

/** Owns the marker syntax: how a region is delimited on a page and how pages are parsed. */
final class Markers
{
    private const TOKEN = '/<!-- (\/?)generated:([^\s>]+) -->/';

    /** Anything that looks like a marker, well-formed or not. */
    private const LOOSE = '/<!--\s*\/?\s*generated:/';

    public static function open(RegionName $name): string
    {
        return "<!-- generated:{$name} -->";
    }

    public static function close(RegionName $name): string
    {
        return "<!-- /generated:{$name} -->";
    }

    /** Printed at the top of every generated block. */
    public static function notice(): string
    {
        return '<!-- Generated by `just docs-generate`; edit the source, not this block. -->';
    }

    /**
     * The marker pairs of a page, in order.
     *
     * @return list<MarkerPair>
     *
     * @throws RuntimeException on unbalanced, nested, duplicate or malformed markers
     */
    public static function pairs(string $content, string $page): array
    {
        preg_match_all(self::TOKEN, $content, $tokens, PREG_SET_ORDER | PREG_OFFSET_CAPTURE);
        $loose = preg_match_all(self::LOOSE, $content);
        if ($loose !== count($tokens)) {
            throw new RuntimeException("{$page} has marker text that is not a well-formed generated marker");
        }

        $pairs = [];
        $seen = [];
        $open = null;
        foreach ($tokens as $token) {
            $closing = $token[1][0] === '/';
            $name = RegionName::fromString($token[2][0]);
            $start = $token[0][1];
            $end = $start + strlen($token[0][0]);

            if (! $closing) {
                // A second open before the first closed is nesting, which a block rewrite cannot honour.
                if ($open !== null) {
                    throw new RuntimeException("{$page} nests region {$name} inside region {$open['name']}");
                }
                if (isset($seen[$name->value])) {
                    throw new RuntimeException("{$page} places region {$name} more than once");
                }
                $seen[$name->value] = true;
                $open = ['name' => $name, 'end' => $end];

                continue;
            }

            if ($open === null) {
                throw new RuntimeException("{$page} closes region {$name} that was never opened");
            }
            if ($open['name']->value !== $name->value) {
                throw new RuntimeException("{$page} closes region {$name} while region {$open['name']} is open");
            }
            $pairs[] = new MarkerPair($name, $open['end'], $start);
            $open = null;
        }

        if ($open !== null) {
            throw new RuntimeException("{$page} never closes region {$open['name']}");
        }

        return $pairs;
    }
}
